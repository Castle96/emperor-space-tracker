"""Fast-ice backscatter from Sentinel-1 C-band SAR.

Why SAR and not optical
-----------------------
During the austral polar night the sun does not rise for months. Optical
imagery is useless, and passive microwave cannot resolve the metre-to-hundred-
metre fracture structure that determines whether a colony's fast ice will hold.
C-band SAR penetrates nothing but is indifferent to the sun: it measures the
*surface* dielectric and roughness, which is exactly what fast ice, nilas, leads
and open water differ by.

The physics the model encodes
-----------------------------
Calibrated sigma0 for the four surface states that matter, from the
Antarctic SAR literature:

==========================  ==========================  ===================
State                       sigma0 HH (dB)             Cause
==========================  ==========================  ===================
Consolidated first-year     -8 to -3                    brine channels and
                            (brighter)                  wind-roughened surface
Rough, ridged ice           -6 to -1                    pressure ridges and
                                                         rafted floes
Thin nilas / new ice        -13 to -9                   low roughness, no
                                                         volume scattering
Open water / lead           -20 to -12                  specular reflection
                                                         away from sensor
==========================  ==========================  ===================

The operational consequence: a *drop* in mean sigma0 between acquisitions
is the standard remote-sensing signature of a lead opening, and a drop in the
*frozen* fraction is the signature of the fast-ice tongue detaching from the
coast. That is what :meth:`~emperor_space_tracker.models.SarScene.classify`
grades, and what the alerting rules key off.

Two backends
------------
``gee``
    Genuine retrieval. Requires ``earthengine-api`` and a completed
    ``earthengine authenticate``. The reduction is a per-scene ``reduceRegion``
    over a colony-centred buffer, so the client only ever pulls a few hundred
    values back, never the raster itself.

``synthetic``
    A physically-motivated simulation: a smooth brine/roughness field, an
    orographic wind-roughening gradient, a lead network generated by a distance
    transform, and seasonal fast-ice decay. It exists so the pipeline, the store
    and the dashboard are fully exercisable with no cloud credentials and no
    egress to Google. Every scene it produces is stamped
    ``provenance="synthetic"`` and the dashboard renders that as a visible badge.
    Synthetic data is never silently presented as observation.
"""

